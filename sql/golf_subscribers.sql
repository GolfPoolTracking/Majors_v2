-- Mailing list for "entries open" / "closing soon" emails (replaces Mailchimp).
-- unsub_token is the secret in each subscriber's unsubscribe link.
create table if not exists public.golf_subscribers (
    email           text primary key,          -- always stored lowercase
    first_name      text,
    last_name       text,
    referred_by     text,
    source          text,                      -- 'Mailchimp import', 'Entry form', 'Signup page', 'Admin'
    subscribed_at   timestamptz not null default now(),
    unsubscribed_at timestamptz,               -- null = subscribed
    unsub_token     uuid not null default gen_random_uuid() unique
);

-- One row per email sent by a campaign, so a re-run never emails anyone twice.
create table if not exists public.golf_email_sends (
    id            bigint generated by default as identity primary key,
    campaign_id   text not null,               -- e.g. '907:entries_open'
    email         text not null,
    status        text not null,               -- 'sent' or 'failed: ...'
    sent_at       timestamptz not null default now(),
    unique (campaign_id, email)
);

-- Same as the other golf_ tables: RLS on with no policies, so only the service key can read or write.
alter table public.golf_subscribers enable row level security;
alter table public.golf_email_sends enable row level security;
